/* Regular (non-fuzzed) regression tests: run the same 3-stage lifecycle with
 * two genuinely different, validly-signed images so a swap is actually
 * observable, proving the sequence behaves correctly on known-good input
 * rather than only being exercised incidentally by the fuzzer. */

void ProvisionPrimaryAndCandidate()
{
    flash_sim_init();
    memcpy(flash_sim_get_mem(), img_out, kTemplateSize);
    const struct flash_area *secondary = nullptr;
    ASSERT_EQ(flash_area_open(2, &secondary), 0);
    memcpy(flash_sim_get_mem() + secondary->fa_off, img_candidate, kTemplateSize);
}

TEST(McuBootSuite, UpgradeConfirmedSwapPersists)
{
    ProvisionPrimaryAndCandidate();
    ASSERT_EQ(boot_set_pending(/*permanent=*/0), 0);

    struct boot_rsp rsp1 = {};
    boot_go(&rsp1);
    ASSERT_TRUE(PrimaryMatches(img_candidate, kTemplateSize))
        << "a valid pending candidate must be swapped into the primary slot";

    ASSERT_EQ(boot_set_confirmed(), 0);

    struct boot_rsp rsp2 = {};
    boot_go(&rsp2);
    EXPECT_TRUE(PrimaryMatches(img_candidate, kTemplateSize))
        << "a confirmed swap must remain in place after a simulated reboot";
}

